/// <summary>
/// 枫丹洋葱汤效果:本回合内,你的[新闻]费用为 0;回合结束整体移除(不走逐层衰减)。
/// </summary>
[RegisterPower]
public sealed class OnionSoupPower : CharlottePowerBase
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override bool TryModifyEnergyCostInCombatLate(CardModel card, decimal originalCost, out decimal modifiedCost)
    {
        modifiedCost = originalCost;
        if (card.Owner.Creature != base.Owner || !News.IsNews(card))
        {
            return false;
        }
        if (card.Pile?.Type != PileType.Hand && card.Pile?.Type != PileType.Play)
        {
            return false;
        }
        modifiedCost = 0m;
        return true;
    }

    public override async Task AfterSideTurnEnd(PlayerChoiceContext choiceContext, CombatSide side, IEnumerable<Creature> participants)
    {
        if (participants.Contains(base.Owner))
        {
            await PowerCmd.Remove(this);
        }
    }
}
