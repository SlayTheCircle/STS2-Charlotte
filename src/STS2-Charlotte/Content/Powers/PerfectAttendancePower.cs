namespace CharlotteMod.Content.Powers;

/// <summary>全勤奖金效果:每回合开始时,获得 Amount 金币。</summary>
[RegisterPower]
public sealed class PerfectAttendancePower : CharlottePowerBase
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task BeforeSideTurnStart(PlayerChoiceContext choiceContext, CombatSide side, IReadOnlyList<Creature> participants, ICombatState combatState)
    {
        if (side == CombatSide.Player && participants.Contains(base.Owner))
        {
            await PlayerCmd.GainGold(base.Amount, base.Owner.Player);
        }
    }
}
